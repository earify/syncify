import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Syncify - self-hosted Obsidian vault sync
*/`;

const prod = process.argv[2] === "production";

/** @type {import('esbuild').BuildOptions} */
const options = {
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "../main.js",
  minify: prod,
  alias: { "@syncify/shared": "../shared/src/index.ts" },
};

if (prod) {
  await esbuild.build(options);
  process.exit(0);
} else {
  const ctx = await esbuild.context(options);
  await ctx.watch();
}
